"""Helpers that assemble a raw store from the committed issuer look-alikes.

Every byte written here comes from ``tests/fixtures/issuers/**`` (fictional
look-alikes) or is generated by ``tests/_qpd_helpers``; no real issuer file or
download is ever used. The helpers also build the deliberately broken copies
that exercise each validation check, one per check, on the same real shapes.
"""

from __future__ import annotations

import json
import shutil
from collections.abc import Sequence
from dataclasses import dataclass
from datetime import UTC, date, datetime
from pathlib import Path
from typing import Any

from openpyxl import load_workbook
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas

from etfh.storage import RawStore
from etfh.types import RawFile
from tests._qpd_helpers import (
    write_bmo_lookalike,
    write_evolve_lookalike,
    write_purpose_lookalike,
    write_vanguard_lookalike,
)

FIXTURES = Path(__file__).resolve().parent / "fixtures" / "issuers"
PURPOSE_LOOKALIKE = FIXTURES / "purpose" / "lookalike.json"
PURPOSE_OPTIONS = FIXTURES / "purpose" / "options.json"
PURPOSE_PARTIAL = FIXTURES / "purpose" / "partial.json"
PURPOSE_TOP_TEN = FIXTURES / "purpose" / "top_ten.json"
PURPOSE_COVERED_CALL = FIXTURES / "purpose" / "covered_call.json"
EVOLVE_CSV = FIXTURES / "evolve" / "lookalike.csv"
BMO_EQUITY = FIXTURES / "bmo" / "equity.xlsx"
BMO_FIXED_INCOME = FIXTURES / "bmo" / "fixed_income.xlsx"
BMO_DUPLICATE_LINES = FIXTURES / "bmo" / "duplicate_lines.xlsx"

FETCHED_AT = datetime(2026, 10, 17, 22, 0, tzinfo=UTC)
DAILY_AS_OF = date(2026, 10, 16)
_XLSX_CONTENT_TYPE = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"


@dataclass(frozen=True, slots=True)
class LookAlike:
    """One look-alike file plus the registry identities it is stored under."""

    source_id: str
    issuer: str
    fund_ticker: str
    path: Path
    as_of_hint: date | None
    ext: str
    content_type: str
    fetched_at: datetime = FETCHED_AT


def clean_look_alikes(tmp_path: Path) -> list[LookAlike]:
    """One committed look-alike per issuer shape, on real source/fund pairs."""
    return [
        _json_file("PDIV", PURPOSE_LOOKALIKE, DAILY_AS_OF),
        _json_file("PDF", PURPOSE_OPTIONS, DAILY_AS_OF),
        _json_file("PID", PURPOSE_PARTIAL, DAILY_AS_OF),
        _json_file("RDE", PURPOSE_TOP_TEN, date(2026, 9, 30)),
        LookAlike(
            "evolve_daily", "evolve", "ESPX", EVOLVE_CSV, date(2026, 10, 7), "csv", "text/csv"
        ),
        _xlsx_file("ZSP", BMO_EQUITY, DAILY_AS_OF),
        _xlsx_file("ZAG", BMO_FIXED_INCOME, DAILY_AS_OF),
        _xlsx_file("ZEM", BMO_DUPLICATE_LINES, DAILY_AS_OF),
        _pdf_file(
            "purpose_qpd", "purpose", "PDF", write_purpose_lookalike(tmp_path / "purpose_qpd.pdf")
        ),
        _pdf_file(
            "evolve_qpd", "evolve", "CYBR", write_evolve_lookalike(tmp_path / "evolve_qpd.pdf")
        ),
        _pdf_file("bmo_qpd", "bmo", "ZSP", write_bmo_lookalike(tmp_path / "bmo_qpd.pdf")),
        _pdf_file(
            "vanguard_ca_qpd",
            "vanguard_ca",
            "VFV",
            write_vanguard_lookalike(tmp_path / "vanguard_qpd.pdf"),
        ),
    ]


def _json_file(fund_ticker: str, path: Path, as_of: date) -> LookAlike:
    return LookAlike(
        "purpose_daily", "purpose", fund_ticker, path, as_of, "json", "application/json"
    )


def covered_call_lookalike(*, fund_ticker: str = "BNC") -> LookAlike:
    """The committed Purpose covered-call look-alike (sum 1.0064, partial list).

    It mirrors the BNC 2026-10-22 shape that D80a admits: the source publishes
    its own weights above 100% with a complete breakdown and no cash row.
    """
    return LookAlike(
        "purpose_daily",
        "purpose",
        fund_ticker,
        PURPOSE_COVERED_CALL,
        date(2026, 10, 22),
        "json",
        "application/json",
        fetched_at=datetime(2026, 10, 22, 22, 0, tzinfo=UTC),
    )


def _xlsx_file(fund_ticker: str, path: Path, as_of: date) -> LookAlike:
    return LookAlike("bmo_daily", "bmo", fund_ticker, path, as_of, "xlsx", _XLSX_CONTENT_TYPE)


def _pdf_file(source_id: str, issuer: str, fund_ticker: str, path: Path) -> LookAlike:
    return LookAlike(source_id, issuer, fund_ticker, path, None, "pdf", "application/pdf")


def write_look_alikes(store: RawStore, items: Sequence[LookAlike]) -> list[RawFile]:
    """Store every look-alike unmodified and return the written raw files."""
    written: list[RawFile] = []
    for item in items:
        written.append(
            store.write(
                item.path.read_bytes(),
                source_id=item.source_id,
                issuer=item.issuer,
                fund_ticker=item.fund_ticker,
                url=f"https://example.invalid/{item.path.name}",
                fetched_at=item.fetched_at,
                ext=item.ext,
                content_type=item.content_type,
                as_of_hint=item.as_of_hint,
            )
        )
    return written


def _purpose_payload(source: Path, destination: Path, mutate: Any) -> Path:
    payload = json.loads(source.read_text(encoding="utf-8"))
    mutate(payload)
    destination.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    return destination


def _scale_purpose_weights(factor: float) -> Any:
    def mutate(payload: dict[str, Any]) -> None:
        for holding in payload["portfolio"]["Level4"]["holdings"]:
            weight = holding.get("weight")
            if isinstance(weight, str) and weight.endswith("%"):
                holding["weight"] = f"{float(weight[:-1]) * factor:.4f}%"

    return mutate


def broken_weight_sum(tmp_path: Path, *, fund_ticker: str = "ZQQ") -> LookAlike:
    """A BMO look-alike whose weights sum to half the portfolio."""
    path = tmp_path / "broken_weight_sum.xlsx"
    shutil.copyfile(BMO_EQUITY, path)
    workbook = load_workbook(path)
    sheet = workbook.active
    for row in sheet.iter_rows(min_row=2, max_row=sheet.max_row):
        cell = row[0]
        if isinstance(cell.value, int | float):
            cell.value = float(cell.value) * 0.5
    workbook.save(path)
    return _xlsx_file(fund_ticker, path, DAILY_AS_OF)


def broken_unit_contradiction(tmp_path: Path, *, fund_ticker: str = "BNC") -> LookAlike:
    """A percent-declared Purpose look-alike whose values total 1.0 percent."""
    path = _purpose_payload(
        PURPOSE_LOOKALIKE, tmp_path / "broken_unit.json", _scale_purpose_weights(0.01)
    )
    return _json_file(fund_ticker, path, DAILY_AS_OF)


def broken_future_as_of(tmp_path: Path, *, fund_ticker: str = "PHR") -> LookAlike:
    """A Purpose look-alike whose portfolio date is after the fetch date."""

    def mutate(payload: dict[str, Any]) -> None:
        payload["portfolio"]["dt"] = "2026-12-01"

    path = _purpose_payload(PURPOSE_LOOKALIKE, tmp_path / "broken_future.json", mutate)
    return _json_file(fund_ticker, path, date(2026, 12, 1))


def broken_duplicate_security(tmp_path: Path, *, fund_ticker: str = "ZCN") -> LookAlike:
    """A BMO look-alike with one cash row duplicated byte-for-byte (D51 error)."""
    path = tmp_path / "broken_duplicate_security.xlsx"
    shutil.copyfile(BMO_EQUITY, path)
    workbook = load_workbook(path)
    sheet = workbook.active
    sheet.append([cells.value for cells in sheet[6]])
    workbook.save(path)
    return _xlsx_file(fund_ticker, path, DAILY_AS_OF)


def duplicate_lines_copy(tmp_path: Path, *, fund_ticker: str = "ZDV") -> LookAlike:
    """A BMO look-alike with the same cash line twice, different shares (D51 info).

    The committed ``duplicate_lines.xlsx`` carries fictional ISINs that fail
    the check digit, so both lines stay unmatched and never reach the D51
    duplicate rule; this copy reaches it through the cash currency id instead.
    """
    path = tmp_path / "duplicate_lines_copy.xlsx"
    shutil.copyfile(BMO_EQUITY, path)
    workbook = load_workbook(path)
    sheet = workbook.active
    cells = [cell.value for cell in sheet[6]]
    cells[4] = (cells[4] or 0) + 1
    sheet.append(cells)
    workbook.save(path)
    return _xlsx_file(fund_ticker, path, DAILY_AS_OF)


def _write_bmo_pdf_with_total(path: Path, total: str) -> Path:
    """Copy of the BMO look-alike layout whose printed total is ``total``."""
    path.parent.mkdir(parents=True, exist_ok=True)
    left, right, top = 72.0, letter[0] - 72.0, letter[1] - 72.0
    pdf = canvas.Canvas(str(path), pagesize=letter, invariant=1)
    pdf.setTitle("Summary of Investment Portfolio")
    pdf.setAuthor("etfh test fixtures")

    def row(y: float, name: str, shares: str, value: str, percent: str) -> None:
        pdf.drawString(left, y, name)
        pdf.drawRightString(340, y, shares)
        pdf.drawRightString(470, y, value)
        pdf.drawRightString(right, y, percent)

    pdf.setFont("Helvetica-Bold", 12)
    pdf.drawString(left, top, "BMO Fictional Canadian Equity Index ETF (ZFN)")
    pdf.setFont("Helvetica-Bold", 11)
    pdf.drawString(left, top - 18, "Summary of Investment Portfolio")
    pdf.setFont("Helvetica", 10)
    pdf.drawString(left, top - 32, "As at March 31, 2026")
    pdf.setFont("Helvetica-Bold", 8)
    pdf.drawString(left, top - 62, "Security Name")
    pdf.drawRightString(340, top - 62, "Number of Shares")
    pdf.drawRightString(470, top - 62, "Market Value ($)")
    pdf.drawRightString(right, top - 62, "% of Net Assets")
    pdf.setFont("Helvetica", 9)
    rows = [
        ("Northgate Bank", "1,234,500", "$ 45,678,900", "44.56%"),
        ("Maplecrest Properties", "987,654", "$ 23,456,700", "32.34%"),
        ("Pineview Software Corp.", "456,789", "$ 12,345,600", "21.23%"),
        ("Cash and Cash Equivalents", "-", "$ 1,000,000", "0.97%"),
    ]
    for index, data in enumerate(rows, start=1):
        row(top - 62 - index * 14, *data)
    pdf.setFont("Helvetica-Bold", 9)
    pdf.drawRightString(right, top - 150, total)
    pdf.save()
    return path


def broken_qpd_stated_total(tmp_path: Path, *, fund_ticker: str = "ZLB") -> LookAlike:
    """A disclosure whose printed total disagrees with its own table."""
    path = _write_bmo_pdf_with_total(tmp_path / "broken_qpd_total.pdf", "Total Investments 50.00%")
    return _pdf_file("bmo_qpd", "bmo", fund_ticker, path)
